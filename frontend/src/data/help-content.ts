export function getAllHelpSections(): HelpSection[] {
  return helpSections;
}

export function getHelpSection(id: string): HelpSection | undefined {
  return helpSections.find((section) => section.id === id);
}

export function searchHelp(query: string): HelpSection[] {
  const q = query.toLowerCase();
  return helpSections
    .map((section) => ({
      ...section,
      topics: section.topics.filter(
        (topic) =>
          topic.title.toLowerCase().includes(q) ||
          topic.content.toLowerCase().includes(q)
      ),
    }))
    .filter((section) => section.topics.length > 0);
}
